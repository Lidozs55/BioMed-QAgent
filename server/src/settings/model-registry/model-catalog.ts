function asEntries(rows: CatalogRow[]): ModelCatalogEntry[] {
  return rows.map(([
    id,
    vendorId,
    contextWindow,
    maxOutputTokens,
    suggestedMaxTokens,
    text,
    image,
    video,
    audio,
  ]) => ({
    id,
    vendor_id: vendorId,
    context_window: contextWindow,
    max_output_tokens: maxOutputTokens,
    suggested_max_tokens: suggestedMaxTokens,
    capabilities: { text, image, video, audio },
  }));
}

export const MODEL_CATALOG: Record<string, ModelCatalogEntry> = Object.fromEntries([
  ...asEntries(RAW_CATALOG),
  ...EXTRA_CATALOG,
].map((entry) => [entry.id, entry]));

const CATALOG_INDEX = new Map<string, ModelCatalogEntry>();
for (const entry of Object.values(MODEL_CATALOG)) {
  CATALOG_INDEX.set(entry.id.toLowerCase(), entry);
  for (const alias of entry.aliases ?? []) {
    CATALOG_INDEX.set(alias.toLowerCase(), entry);
  }
}

export function lookupModelCatalog(modelId: string): ModelCatalogEntry | undefined {
  return CATALOG_INDEX.get(modelId.toLowerCase());
}

/** Non-chat/generation models in the catalog use 1 as a sentinel; surface as unknown. */
export function catalogCapacity(value: number | null): number | null {
  return value !== null && value > 1 ? value : null;
}

export function catalogContextWindow(entry: ModelCatalogEntry): number | null {
  return catalogCapacity(entry.context_window);
}
